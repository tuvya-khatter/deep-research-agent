class TestWrite:
    def _make_metadata(self, tmp_path: Path) -> OutputMetadata:
        return OutputMetadata(
            query="quantum computing",
            model_id="claude-test",
            session_id="sess-1",
            query_id="q-1",
            generated_at=_FIXED_TS,
            source_count=1,
        )

    def test_writes_file_and_returns_path(self, manager: OutputManager, tmp_output_dir: Path) -> None:
        metadata = self._make_metadata(tmp_output_dir)
        path = manager.write(
            response_text="Research content.",
            query="quantum computing",
            sources=[Source(url="https://a.com", title="A")],
            metadata=metadata,
            output_dir=tmp_output_dir,
        )
        assert path.exists()
        assert path.suffix == ".md"
        content = path.read_text(encoding="utf-8")
        assert "quantum computing" in content

    def test_creates_missing_output_dir(self, manager: OutputManager, tmp_path: Path) -> None:
        new_dir = tmp_path / "nested" / "output"
        metadata = OutputMetadata(
            query="test", model_id="m", session_id="s", query_id="q",
            generated_at=_FIXED_TS, source_count=0,
        )
        path = manager.write("text", "test", [], metadata, new_dir)
        assert path.exists()

    def test_raises_output_error_on_permission_failure(
        self, manager: OutputManager, tmp_output_dir: Path
    ) -> None:
        metadata = OutputMetadata(
            query="test", model_id="m", session_id="s", query_id="q",
            generated_at=_FIXED_TS, source_count=0,
        )
        with patch.object(manager, "_ensure_output_dir", side_effect=OutputError("no perms")):
            with pytest.raises(OutputError):
                manager.write("text", "test", [], metadata, tmp_output_dir)


