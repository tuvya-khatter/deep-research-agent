# ---------------------------------------------------------------------------
# _sanitize_slug — example-based
# ---------------------------------------------------------------------------

class TestSanitizeSlug:
    def test_spaces_become_hyphens(self, manager: OutputManager) -> None:
        assert manager._sanitize_slug("quantum computing") == "quantum-computing"

    def test_special_chars_stripped(self, manager: OutputManager) -> None:
        assert manager._sanitize_slug("What is C++?") == "what-is-c"

    def test_truncated_to_50(self, manager: OutputManager) -> None:
        long = "a" * 100
        result = manager._sanitize_slug(long)
        assert len(result) <= 50

    def test_empty_returns_research(self, manager: OutputManager) -> None:
        assert manager._sanitize_slug("") == "research"

    def test_all_non_alpha_returns_research(self, manager: OutputManager) -> None:
        assert manager._sanitize_slug("???!!!") == "research"

    def test_no_leading_trailing_hyphens(self, manager: OutputManager) -> None:
        result = manager._sanitize_slug("  hello world  ")
        assert not result.startswith("-")
        assert not result.endswith("-")

    def test_consecutive_hyphens_collapsed(self, manager: OutputManager) -> None:
        result = manager._sanitize_slug("hello   world")
        assert "--" not in result


