class TestFormatMarkdown:
    def _make_metadata(self) -> OutputMetadata:
        return OutputMetadata(
            query="What is quantum computing?",
            model_id="claude-test",
            session_id="sess-1",
            query_id="q-1",
            generated_at=_FIXED_TS,
            source_count=2,
        )

    def test_all_required_sections_present(self, manager: OutputManager) -> None:
        sources = [Source(url="https://a.com", title="A")]
        content = manager._format_markdown("Response text.", sources, self._make_metadata())
        for section in _REQUIRED_SECTIONS:
            assert section in content, f"Missing section: {section}"

    def test_contains_query(self, manager: OutputManager) -> None:
        content = manager._format_markdown("text", [], self._make_metadata())
        assert "quantum computing" in content

    def test_sources_listed(self, manager: OutputManager) -> None:
        sources = [Source(url="https://a.com", title="Source A")]
        content = manager._format_markdown("text", sources, self._make_metadata())
        assert "https://a.com" in content
        assert "Source A" in content

    def test_no_sources_shows_placeholder(self, manager: OutputManager) -> None:
        content = manager._format_markdown("text", [], self._make_metadata())
        assert "No sources recorded" in content

    def test_incomplete_marker_preserved(self, manager: OutputManager) -> None:
        text = "partial response\n\n---\n**[INCOMPLETE — stream interrupted]**"
        content = manager._format_markdown(text, [], self._make_metadata())
        assert "[INCOMPLETE" in content


