@pytest.mark.pbt
@given(query=valid_slug_input())
def test_property_sanitize_slug_length(query: str) -> None:
    """Invariant: slug length never exceeds 50 characters."""
    manager = OutputManager()
    result = manager._sanitize_slug(query)
    assert len(result) <= 50, f"Slug too long ({len(result)}): {result!r}"


@pytest.mark.pbt
@given(query=valid_slug_input())
def test_property_sanitize_slug_charset(query: str) -> None:
    """Invariant: slug contains only [a-z0-9-] and is non-empty."""
    manager = OutputManager()
    result = manager._sanitize_slug(query)
    assert result != "", "Slug must never be empty (fallback 'research' expected)"
    assert re.fullmatch(r"[a-z0-9][a-z0-9-]*[a-z0-9]|[a-z0-9]", result), (
        f"Slug contains invalid characters: {result!r}"
    )


@pytest.mark.pbt
@given(query=valid_slug_input())
def test_property_sanitize_slug_idempotent(query: str) -> None:
    """Idempotence: sanitize(sanitize(q)) == sanitize(q)."""
    manager = OutputManager()
    once = manager._sanitize_slug(query)
    twice = manager._sanitize_slug(once)
    assert once == twice, f"Not idempotent: {once!r} -> {twice!r}"


@pytest.mark.pbt
@given(
    response_text=st.text(min_size=0, max_size=500),
    sources=source_list(),
    metadata=output_metadata_strategy(),
)
def test_property_format_markdown_sections(
    response_text: str, sources: list[Source], metadata: OutputMetadata
) -> None:
    """Invariant: all required sections always present in Markdown output."""
    manager = OutputManager()
    content = manager._format_markdown(response_text, sources, metadata)
    for section in _REQUIRED_SECTIONS:
        assert section in content, f"Required section missing: {section!r}"


@pytest.mark.pbt
@given(
    response_text=st.text(min_size=0, max_size=200),
    sources=source_list(),
    metadata=output_metadata_strategy(),
)
def test_property_format_markdown_source_count(
    response_text: str, sources: list[Source], metadata: OutputMetadata
) -> None:
    """Invariant: source_count in metadata matches len(sources)."""
    # Rebuild metadata with correct source_count
    from dataclasses import replace
    metadata = replace(metadata, source_count=len(sources))
    manager = OutputManager()
    content = manager._format_markdown(response_text, sources, metadata)
    assert str(len(sources)) in content
