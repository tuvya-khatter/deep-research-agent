# ---------------------------------------------------------------------------
# _resolve_filename — collision handling
# ---------------------------------------------------------------------------

class TestResolveFilename:
    def test_no_collision_returns_base(self, manager: OutputManager, tmp_path: Path) -> None:
        path = manager._resolve_filename(tmp_path, "test", _FIXED_TS)
        assert path.name == "test_20260525_143022.md"

    def test_collision_appends_counter(self, manager: OutputManager, tmp_path: Path) -> None:
        base = tmp_path / "test_20260525_143022.md"
        base.write_text("existing")
        path = manager._resolve_filename(tmp_path, "test", _FIXED_TS)
        assert path.name == "test_20260525_143022_1.md"

    def test_multiple_collisions(self, manager: OutputManager, tmp_path: Path) -> None:
        (tmp_path / "test_20260525_143022.md").write_text("")
        (tmp_path / "test_20260525_143022_1.md").write_text("")
        path = manager._resolve_filename(tmp_path, "test", _FIXED_TS)
        assert path.name == "test_20260525_143022_2.md"


